export function getEnchantmentImagePath(name, category) {
  if (category === 'Ranged' && ENCHANT_RANGED_OVERRIDE[name]) {
    return `/mcd icons/enchantments/${ENCHANT_RANGED_OVERRIDE[name]}`;
  }
  if (ENCHANT_FILE_MAP[name]) {
    return `/mcd icons/enchantments/${ENCHANT_FILE_MAP[name]}`;
  }
  const slug = name.replace(/ /g, '_').replace(/'/g, '');
  return `/mcd icons/enchantments/MCD_${slug}.png`;
}

